// Writes the public legal pages from the app's legal text:
//   node scripts/build-legal.mjs   → privacy/index.html, terms/index.html
// The pages are static (no scripts) in the /support page's style; the text
// comes only from src/app/legal/content.js. tests/legal-pages.test.mjs fails
// when a committed page is out of date.

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { LEGAL, CONTACT } from '../src/app/legal/content.js';

const DESCRIPTIONS = {
  privacy: 'How Sonmira handles your recordings, words, paintings, purchases and identifiers.',
  terms: 'The terms for using Sonmira, the personal singing diary.',
};

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// Email addresses and https:// URLs become links (a trailing period or
// parenthesis is punctuation, not part of the URL).
const linkify = (s) => esc(s)
  .replace(/https:\/\/[^\s)]+?(?=[.,;]?(?:\s|\)|$))/g, (u) => `<a href="${u}">${u.replace(/^https:\/\//, '').replace(/\/$/, '')}</a>`)
  .replace(/[\w.+-]+@[\w-]+\.[\w.]+\w/g, (e) => `<a href="mailto:${e}">${e}</a>`);

const block = (b) => (typeof b === 'string'
  ? `  <p>${linkify(b)}</p>`
  : `  <ul>\n${b.list.map((t) => `    <li>${linkify(t)}</li>`).join('\n')}\n  </ul>`);

export function renderLegalPage(kind) {
  const d = LEGAL[kind];
  const summary = d.summary
    ? `\n  <div class="card">\n    <p><strong>In short</strong></p>\n${block({ list: d.summary }).replace(/^/gm, '  ')}\n  </div>\n`
    : '';
  const sections = d.sections.map((s) => `\n  <h2>${esc(s.heading)}</h2>\n${s.blocks.map(block).join('\n')}`).join('\n');
  return `<!DOCTYPE html>
<!-- Generated by scripts/build-legal.mjs from src/app/legal/content.js. Edit that file, then run: node scripts/build-legal.mjs -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#F8F5EF">
<title>Sonmira ${esc(d.title)}</title>
<meta name="description" content="${esc(DESCRIPTIONS[kind])}">
<link rel="icon" href="/support/icon-180.png">
<link rel="apple-touch-icon" href="/support/icon-180.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Cormorant+Garamond:wght@500;600&family=Hanken+Grotesk:wght@400..600&display=swap" rel="stylesheet">
<style>
  /* Public legal page: same layout as /support, self-contained, no scripts. */
  :root {
    --paper: #F8F5EF; --tile: #F5F1EA; --tile-line: #E6DFD3;
    --ink: #1F1D1A; --body: #5E5850; --secondary: #8C867D; --underline: #DDD6CA;
    --serif: 'Cormorant Garamond', 'Iowan Old Style', Georgia, serif;
    --sans: 'Hanken Grotesk', -apple-system, system-ui, sans-serif;
  }
  * { box-sizing: border-box; }
  html, body { margin: 0; background: var(--paper); color: var(--ink); }
  body {
    font-family: var(--sans); font-size: 16px; line-height: 1.6;
    -webkit-font-smoothing: antialiased; -webkit-text-size-adjust: 100%;
    min-height: 100vh; min-height: 100dvh; display: flex; flex-direction: column;
    padding: max(48px, env(safe-area-inset-top)) max(24px, env(safe-area-inset-right)) max(32px, env(safe-area-inset-bottom)) max(24px, env(safe-area-inset-left));
  }
  main { width: 100%; max-width: 640px; margin: 0 auto; flex: 1; }
  .brand { display: flex; align-items: center; gap: 10px; color: var(--secondary); font-size: 14px; letter-spacing: .02em; margin-bottom: 40px; text-decoration: none; }
  .brand img { width: 32px; height: 32px; border-radius: 8px; box-shadow: 0 0 0 1px var(--tile-line); }
  h1 { font-family: var(--serif); font-weight: 500; font-size: 40px; line-height: 1.1; margin: 0 0 12px; letter-spacing: -.01em; }
  h2 { font-family: var(--serif); font-weight: 600; font-size: 25px; line-height: 1.2; margin: 40px 0 12px; }
  p, li { color: var(--body); }
  p { margin: 0 0 16px; }
  ul { margin: 0 0 16px; padding-left: 20px; }
  li { margin-bottom: 8px; }
  strong { color: var(--ink); font-weight: 600; }
  a { color: var(--ink); text-decoration: underline; text-decoration-color: var(--underline); text-underline-offset: 3px; overflow-wrap: anywhere; }
  .updated { font-size: 14px; color: var(--secondary); margin-bottom: 24px; }
  .card { background: var(--tile); border: 1px solid var(--tile-line); border-radius: 16px; padding: 20px; margin: 24px 0; }
  .card p:last-child, .card ul:last-child { margin-bottom: 0; }
  .label { font-size: 13px; color: var(--secondary); margin-bottom: 4px; }
  .email { font-size: 18px; font-weight: 500; }
  footer { width: 100%; max-width: 640px; margin: 48px auto 0; font-size: 13px; color: var(--secondary); display: flex; gap: 16px; flex-wrap: wrap; }
  footer a { color: var(--secondary); }
</style>
</head>
<body>
<main>
  <a class="brand" href="/support"><img src="/support/icon-180.png" alt="" width="32" height="32">Sonmira</a>
  <h1>${esc(d.title)}</h1>
  <p class="updated">Last updated: ${esc(d.updated)}</p>
${d.intro.map((t) => block(t)).join('\n')}
${summary}${sections}

  <div class="card">
    <div class="label">Email</div>
    <a class="email" href="mailto:${CONTACT}">${CONTACT}</a>
  </div>
</main>
<footer><span>&copy; Sonmira</span><a href="/support">Support</a><a href="/privacy">Privacy Policy</a><a href="/terms">Terms of Service</a></footer>
</body>
</html>
`;
}

export const PAGES = { privacy: 'privacy/index.html', terms: 'terms/index.html' };

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { mkdir } = await import('node:fs/promises');
  const root = new URL('../', import.meta.url);
  for (const [kind, path] of Object.entries(PAGES)) {
    await mkdir(new URL(path.replace(/[^/]+$/, ''), root), { recursive: true });
    await writeFile(new URL(path, root), renderLegalPage(kind));
    console.log('wrote', path);
  }
}
