// Derives the renderer's tier anchors from src/engine/art/annotations.json
// and writes src/engine/art/style-clusters.js (+ style_clusters.json).
// Run after re-annotating: node tools/derive-style.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../src/engine/art/', import.meta.url);
const ann = JSON.parse(readFileSync(new URL('annotations.json', root)));
const TIERS = ['loose', 'gathered', 'resolved'];
const r3 = (x) => Math.round(x * 1000) / 1000;

const get = {
  legibility: (r) => r.form_clarity,
  valueContrast: (r) => r.measured.value_contrast,
  structure: (r) => r.measured.structure,
  whitespace: (r) => r.measured.whitespace,
  fineTexture: (r) => r.measured.fine_texture,
  edgeBleed: (r) => r.scores.edge_bleed,
  linework: (r) => r.scores.linework,
  drips: (r) => r.scores.drips,
  spatter: (r) => r.scores.spatter,
  saturation: (r) => r.measured.saturation,
};

const clusters = {};
for (const t of TIERS) {
  const rs = ann.references.filter((r) => r.level === t);
  const stats = {};
  for (const [k, f] of Object.entries(get)) {
    const v = rs.map(f);
    const mean = v.reduce((a, b) => a + b, 0) / v.length;
    stats[k] = { mean: r3(mean), min: r3(Math.min(...v)), max: r3(Math.max(...v)) };
  }
  clusters[t] = { n: rs.length, ids: rs.map((r) => r.id), stats };
}

const out = {
  note: 'Generated by tools/derive-style.mjs from annotations.json. Means are per user-labelled tier; min/max keep the variation inside each tier.',
  clusters,
};
writeFileSync(new URL('style_clusters.json', root), JSON.stringify(out, null, 1));
writeFileSync(new URL('style-clusters.js', root),
  `// GENERATED by tools/derive-style.mjs from annotations.json — do not edit.\n` +
  `// Per-tier statistics of the 22 user-labelled references (see style_clusters.json).\n` +
  `export const STYLE_CLUSTERS = ${JSON.stringify(clusters, null, 1)};\n`);
for (const t of TIERS) console.log(t, Object.fromEntries(Object.entries(clusters[t].stats).map(([k, v]) => [k, v.mean])));
