"""Index the reference library: discover images, assign families, extract palettes.

Usage:
  python3 tools/index_references.py <refs_root> [--assign <path>=<FAMILY> ...] [--deactivate <id> ...] [--activate <id> ...]
  python3 tools/index_references.py --measure <image>   (prints the palette JSON; used by tools/references.mjs)

The registry src/engine/direct/references.js is the single source of truth for
which reference belongs to which family. This tool keeps it in step with the
folder, so adding a reference never needs a code change:

  * Every image under <refs_root> (jpg, jpeg, png, webp) is discovered.
  * A known image keeps its family, active flag and any curated hints.
  * A new image is assigned from a folder named after a family, either its
    full id or its short code (e.g. <refs_root>/resolved/R4/new.jpg or
    .../R4-lyrical-everyday/new.jpg), or from --assign. Anything else is
    listed as unassigned and stays inactive until assigned.
  * An image that is gone from disk is marked inactive (missing).
  * Colour data is measured from the pixels for every image: dominant,
    secondary and accent colours with their share of the painted area, open
    paper and dark shares, lightness, saturation and temperature. No colour
    description is written by hand.
"""
import colorsys, json, re, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / 'src/engine/direct/references.js'  # --registry overrides (tests)
FAMILIES_JS = ROOT / 'src/engine/direct/families.js'
EXTS = {'.jpg', '.jpeg', '.png', '.webp'}
HEADER = """// Reference library: the single source of truth for which reference image
// belongs to which visual family. GENERATED by tools/index_references.py,
// which discovers images, assigns new ones and measures their colour from the
// pixels. Edit `family` or `active` here, or re-run the tool; generation code
// never lists references itself.
//
//   id       unique, the file name without extension
//   family   visual family id (families.js)
//   path     relative to the reference root ($SONMIRA_REFS_DIR / --refs)
//   active   false keeps it out of selection (unassigned, retired or missing)
//   palette  measured: colors [{hex, share}] dominant first, accent, paper,
//            dark, lightness, saturation, temperature (shares are 0..1)
//   light, motif  optional curated hints
"""


def family_ids():
    return re.findall(r"^  '([A-Z]\d-[a-z-]+)': \{", FAMILIES_JS.read_text(), re.M)


def load_registry():
    if not REGISTRY.exists():
        return []
    m = re.search(r'/\*BEGIN\*/(.*)/\*END\*/', REGISTRY.read_text(), re.S)
    return json.loads(m.group(1)) if m else []


def save_registry(entries):
    body = json.dumps(entries, indent=1, ensure_ascii=False)
    REGISTRY.write_text(f"{HEADER}\nexport const REFERENCE_LIBRARY = /*BEGIN*/{body}/*END*/;\n")


def hexof(rgb):
    return '#%02x%02x%02x' % tuple(int(round(v)) for v in rgb)


def measure(path):
    im = Image.open(path).convert('RGB')
    im.thumbnail((160, 160))
    px = list(im.get_flattened_data() if hasattr(im, 'get_flattened_data') else im.getdata())
    n = len(px)
    hls = [colorsys.rgb_to_hls(*(v / 255 for v in p)) for p in px]
    paper = [i for i, (h, l, s) in enumerate(hls) if l > 0.88 and (s < 0.35 or l > 0.94)]
    dark = sum(1 for h, l, s in hls if l < 0.25)
    paint_idx = sorted(set(range(n)) - set(paper))
    lightness = sum(l for _, l, _ in hls) / n
    sat_vals = [hls[i][2] * (1 - abs(2 * hls[i][1] - 1)) for i in paint_idx] or [0]
    saturation = sum(sat_vals) / len(sat_vals)
    # Temperature: warm (red..yellow) vs cool (green-cyan..violet) chroma.
    warm = cool = 0.0
    for i in paint_idx:
        h, l, s = hls[i]
        c = s * (1 - abs(2 * l - 1))
        deg = h * 360
        if deg < 70 or deg >= 330: warm += c
        elif 150 <= deg < 300: cool += c
    temp = 'warm' if warm > cool * 1.4 else 'cool' if cool > warm * 1.4 else 'neutral'

    colors, accent = [], None
    if paint_idx:
        sub = Image.new('RGB', (len(paint_idx), 1))
        sub.putdata([px[i] for i in paint_idx])
        q = sub.quantize(colors=24, method=Image.Quantize.MEDIANCUT, kmeans=3)
        pal = q.getpalette()
        # Group clusters by hue (12 bins plus greys) and by dark / mid / light,
        # so an average never mixes hues into grey and the tonal steps of one
        # hue stay apart; each group's colour is the share-weighted mean.
        fam = {}
        for cnt, k in q.getcolors():
            rgb = tuple(pal[k * 3:k * 3 + 3])
            h, l, s_ = colorsys.rgb_to_hls(*(v / 255 for v in rgb))
            chroma = s_ * (1 - abs(2 * l - 1))
            band = 0 if l < 0.4 else 1 if l < 0.72 else 2
            key = ('grey' if chroma < 0.05 else int(((h * 360 + 15) % 360) // 30), band)
            f = fam.setdefault(key, [0, [0, 0, 0]])
            f[0] += cnt
            for j in range(3): f[1][j] += rgb[j] * cnt
        merged = sorted(([cnt / n, tuple(v / cnt for v in tot)] for cnt, tot in fam.values()), key=lambda m: -m[0])
        main = [m for m in merged if m[0] >= 0.06][:3] or merged[:1]
        colors = [{'hex': hexof(rgb), 'share': round(share, 3)} for share, rgb in main]

        # Accent: a small, clearly more saturated colour whose hue differs from
        # the main colours; measured on single pixels so tiny touches count.
        def hue_of(rgb):
            return colorsys.rgb_to_hls(*(v / 255 for v in rgb))[0]
        main_hues = [hue_of(rgb) for _, rgb in main]
        vivid = [px[i] for i in paint_idx if hls[i][2] > 0.55 and 0.25 < hls[i][1] < 0.8
                 and all(min(abs(hls[i][0] - h), 1 - abs(hls[i][0] - h)) > 0.08 for h in main_hues)]
        if 0.003 * n <= len(vivid) <= 0.12 * n:
            avg = [sum(c[k] for c in vivid) / len(vivid) for k in range(3)]
            accent = {'hex': hexof(avg), 'share': round(len(vivid) / n, 3)}
    return {
        'colors': colors, 'accent': accent,
        'paper': round(len(paper) / n, 3), 'dark': round(dark / n, 3),
        'lightness': round(lightness, 3), 'saturation': round(saturation, 3), 'temperature': temp,
    }


def main(argv):
    if not argv:
        print(__doc__); return 2
    if argv[0] == '--measure':
        print(json.dumps(measure(Path(argv[1])))); return 0
    root = Path(argv[0])
    global REGISTRY
    opts = {'--assign': [], '--deactivate': [], '--activate': [], '--registry': []}
    key = None
    for a in argv[1:]:
        if a in opts: key = a
        elif key: opts[key].append(a)
    if opts['--registry']: REGISTRY = Path(opts['--registry'][0]).resolve()
    fams = family_ids()
    by_code = {f.split('-')[0]: f for f in fams} | {f: f for f in fams}
    assign = dict(a.split('=', 1) for a in opts['--assign'])

    entries = {e['path']: e for e in load_registry()}
    on_disk = sorted(p.relative_to(root).as_posix() for p in root.rglob('*') if p.suffix.lower() in EXTS and p.is_file())
    unassigned = []
    for rel in on_disk:
        e = entries.get(rel)
        if not e:
            fam = assign.get(rel) or next((by_code[s] for s in rel.split('/')[:-1] if s in by_code), None)
            ids = {x['id'] for x in entries.values()}
            rid = Path(rel).stem if Path(rel).stem not in ids else rel.rsplit('.', 1)[0].replace('/', '_')
            e = entries[rel] = {'id': rid, 'family': fam, 'path': rel, 'active': bool(fam)}
            if not fam: unassigned.append(rel)
        elif rel in assign:
            e['family'] = assign[rel]; e['active'] = True
        e.pop('missing', None)
        e['palette'] = measure(root / rel)
    for rel, e in entries.items():
        if rel not in on_disk:
            e['active'] = False; e['missing'] = True
    for e in entries.values():
        if e['id'] in opts['--deactivate']: e['active'] = False
        if e['id'] in opts['--activate'] and e.get('family') and not e.get('missing'): e['active'] = True
        if e.get('family') and e['family'] not in fams:
            print(f"warning: {e['id']} names unknown family {e['family']}; inactive"); e['active'] = False

    out = sorted(entries.values(), key=lambda e: (e.get('family') or '~', e['id']))
    save_registry(out)
    active = [e for e in out if e['active']]
    print(f"{len(active)} active references in {len({e['family'] for e in active})} families → {REGISTRY}")
    for rel in unassigned:
        print(f"unassigned (inactive): {rel}  → put it in a family folder or pass --assign {rel}=<FAMILY>")
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
